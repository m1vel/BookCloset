// Exercises the fixed-page engine: PDF scroll/spread, text selection + highlight, search, outline; comics; DjVu.
const open = async (page, wait, pred) => {
  const id = await page.evaluate(src => {
    const f = new Function('b', `return (${src})(b)`)
    return window.__bc.lib.getState().books.find(b => f(b))?.id
  }, pred.toString())
  await page.evaluate(id => window.__bc.openBookById(id), id)
  await page.waitForSelector('.paged-scroll', { timeout: 20000 })
  await wait(2500)
}
const back = async (page, wait) => {
  await page.evaluate(() => window.__bc.ui.getState().navigate({ name: 'library', filter: { kind: 'all' } }))
  await wait(500)
}

export default async ({ page, shot, wait }) => {
  await page.waitForSelector('.sidebar', { timeout: 15000 })
  await page.evaluate(() => window.__bc.settings.getState().setPaged({ mode: 'scroll', fit: 'width', zoom: 1 }))

  // ---- PDF (Pushkin, generated by Chromium: has a text layer)
  await open(page, wait, b => b.format === 'pdf' && b.fileName.startsWith('Пушкин'))
  await page.mouse.move(700, 10); await page.mouse.move(700, 20)
  await wait(300)
  await shot('pg-01-pdf-scroll')
  await page.mouse.wheel(0, 1600)
  await wait(1200)
  // drag-select on the text layer
  await page.mouse.move(420, 380)
  await page.mouse.down()
  await page.mouse.move(820, 430, { steps: 14 })
  await page.mouse.up()
  await wait(500)
  await shot('pg-02-pdf-select')
  const dot = await page.$('.sel-dot >> nth=2')
  if (dot) { await dot.click(); await wait(500) }
  await page.mouse.move(700, 600)
  await shot('pg-03-pdf-highlight')
  // search
  await page.keyboard.press('Control+f')
  await wait(300)
  await page.keyboard.type('Гринев')
  await page.keyboard.press('Enter')
  await wait(4000)
  const hit = await page.$('.hit >> nth=3')
  if (hit) { await hit.click(); await wait(1500) }
  await shot('pg-04-pdf-search')
  await page.keyboard.press('Escape')
  // spread mode
  await page.evaluate(() => window.__bc.settings.getState().setPaged({ mode: 'spread', fit: 'page' }))
  await wait(1800)
  await page.mouse.move(700, 10); await page.mouse.move(700, 20)
  await shot('pg-05-pdf-spread')
  await page.evaluate(() => window.__bc.settings.getState().setPaged({ mode: 'scroll', fit: 'width' }))
  await back(page, wait)

  // ---- PDF with outline and links
  await open(page, wait, b => b.format === 'pdf' && b.fileName.startsWith('Attention'))
  await page.mouse.move(700, 10); await page.mouse.move(700, 20)
  await wait(300)
  await page.click('[aria-label="Оглавление"]')
  await wait(800)
  await shot('pg-06-pdf-outline')
  const item = await page.$('.toc-label >> nth=4')
  if (item) { await item.click(); await wait(1800) }
  await shot('pg-07-pdf-outline-nav')
  await back(page, wait)

  // ---- comic (CBZ): single page, next page, spread
  await open(page, wait, b => b.format === 'cbz')
  await page.keyboard.press('ArrowRight')
  await wait(1200)
  await page.mouse.move(700, 10); await page.mouse.move(700, 20)
  await shot('pg-08-comic-page2')
  await page.evaluate(() => window.__bc.settings.getState().setComic({ mode: 'spread' }))
  await wait(1500)
  await shot('pg-09-comic-spread')
  await page.evaluate(() => window.__bc.settings.getState().setComic({ mode: 'single' }))
  await back(page, wait)

  // ---- DjVu: page 3, select text
  await open(page, wait, b => b.format === 'djvu')
  await page.mouse.wheel(0, 2400)
  await wait(2500)
  await page.mouse.move(380, 420)
  await page.mouse.down()
  await page.mouse.move(900, 470, { steps: 14 })
  await page.mouse.up()
  await wait(600)
  await shot('pg-10-djvu-select')
  await back(page, wait)
}

// Online metadata: per-book catalog search dialog (Open Library + Google Books) and bulk cover lookup.
export default async ({ page, shot, wait }) => {
  await page.waitForSelector('.sidebar', { timeout: 15000 })
  await page.evaluate(() => window.__bc.settings.getState().update(s => { s.uiTheme = 'paper'; s.lang = 'ru'; s.schedule.mode = 'off'; s.library.view = 'grid'; s.library.group = 'none' }))
  const target = await page.evaluate(() => {
    const b = window.__bc.lib.getState().books.find(b => b.format === 'rtf' && b.title.includes('Капитанская'))
    return { id: b.id, hasCover: b.hasCover }
  })
  console.log('target before:', target)
  await page.evaluate(id => window.__bc.ui.getState().showDetails(id), target.id)
  await wait(700)
  await page.click('.details-title-actions button:has-text("Найти в интернете")')
  await page.waitForSelector('.meta-card.skeleton', { timeout: 5000 }).catch(() => {})
  await shot('onl-01-loading')
  await page.waitForSelector('.meta-card:not(.skeleton)', { timeout: 30000 })
  await page.waitForFunction(() => document.querySelectorAll('.meta-thumb img').length >= 2, null, { timeout: 30000 }).catch(() => {})
  await page.waitForSelector('.meta-preview .desc-html, .meta-preview .faint', { timeout: 20000 }).catch(() => {})
  await wait(600)
  const cards = await page.$$eval('.meta-card', els => els.map(e => `${e.classList.contains('selected') ? '*' : ' '} ${e.querySelector('.meta-source')?.textContent} | ${e.querySelector('.meta-title')?.textContent} | ${e.querySelector('.meta-authors')?.textContent}`))
  console.log('results:\n' + cards.slice(0, 8).join('\n'))
  await shot('onl-02-results')
  // dark theme rendering of the dialog
  await page.evaluate(() => window.__bc.settings.getState().update(s => { s.uiTheme = 'midnight' }))
  await wait(500)
  await shot('onl-03-results-midnight')
  await page.evaluate(() => window.__bc.settings.getState().update(s => { s.uiTheme = 'paper' }))
  // apply cover + description
  await page.click('.meta-actions .btn.primary')
  await page.waitForSelector('.meta-dialog', { state: 'detached', timeout: 30000 })
  await wait(900)
  const after = await page.evaluate(id => {
    const b = window.__bc.lib.getState().books.find(b => b.id === id)
    return { hasCover: b.hasCover, color: b.coverColor, published: b.published, desc: (b.description ?? '').slice(0, 80) }
  }, target.id)
  console.log('target after:', after)
  await shot('onl-04-applied')
  await page.keyboard.press('Escape')
  await wait(400)
  // a query with no results
  const other = await page.evaluate(() => window.__bc.lib.getState().books.find(b => b.format === 'chm').id)
  await page.evaluate(id => window.__bc.ui.getState().showDetails(id), other)
  await wait(500)
  await page.click('.details-title-actions button:has-text("Найти в интернете")')
  await page.fill('.meta-search input >> nth=0', 'zzqx nonexistent bookcloset title')
  await page.fill('.meta-search input >> nth=1', '')
  await page.click('.meta-search button[type=submit]')
  await page.waitForSelector('.meta-empty', { timeout: 30000 })
  await shot('onl-05-empty')
  await page.keyboard.press('Escape')
  await wait(300)
  console.log('details still open after Esc in dialog:', !!(await page.$('.drawer.details')))
  await page.keyboard.press('Escape')
  await wait(300)
  // bulk lookup from the add menu
  const missing = await page.evaluate(() => window.__bc.lib.getState().books.filter(b => !b.hasCover).length)
  console.log('books without cover:', missing)
  await page.click('.split-caret')
  await wait(400)
  await shot('onl-06a-menu')
  await page.click('.menu-item:has-text("Найти недостающие обложки")')
  await wait(2500)
  await shot('onl-06-bulk-progress')
  await page.waitForFunction(() => [...document.querySelectorAll('.toast')].some(t => /Найдено обложек/.test(t.textContent)), null, { timeout: 240000 })
  const bulk = await page.evaluate(() => window.__bc.lib.getState().books.map(b => `${b.hasCover ? 'C' : '-'} ${b.format} ${b.title}`))
  console.log(bulk.join('\n'))
  await page.evaluate(() => document.querySelector('.lib-scroll')?.scrollTo(0, 400))
  await wait(800)
  await shot('onl-07-bulk-done')
}
